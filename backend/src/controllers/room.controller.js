const mongoose = require('mongoose');
const Room = require('../models/room.model');
const memoryStore = require('../services/memoryStore');

// Helper to generate a 5-digit mix of Capital Letters and Numbers (e.g. "K7M2P")
const generate5DigitPassword = () => {
  const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; // excluding confusing I, O, 0, 1
  let result = '';
  for (let i = 0; i < 5; i++) {
    result += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  return result;
};

// Helper to generate unique room id (e.g. "ROOM-892147")
const generateRoomId = () => {
  const num = Math.floor(100000 + Math.random() * 900000);
  return `ROOM-${num}`;
};

// Helper to format date and time cleanly
const getFormattedDateTime = () => {
  const now = new Date();
  const dateStr = now.toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric'
  });
  const timeStr = now.toLocaleTimeString('en-US', {
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: true
  });
  return { dateStr, timeStr };
};

const isMongoConnected = () => mongoose.connection.readyState === 1;

/**
 * Create a new Room
 * Requirements:
 * - Roomname
 * - Security radiobutton: 1. Public, 2. Private
 * - If Private: autogenerate 5-digit password (capital letters + numbers)
 * - Autogenerated roomid stored in DB
 * - roomHostid, room created on date, room created on time
 */
exports.createRoom = async (req, res) => {
  try {
    const { roomname, isPrivate } = req.body;
    const { userid, username } = req.user;

    if (!roomname || roomname.trim().length === 0) {
      return res.status(400).json({ success: false, message: 'Room name is required.' });
    }

    const { dateStr, timeStr } = getFormattedDateTime();
    const roomid = generateRoomId();

    let password = '';
    const isPrivateBool = isPrivate === true || isPrivate === 'true' || isPrivate === 'private';
    if (isPrivateBool) {
      password = generate5DigitPassword();
    }

    const roomData = {
      roomid,
      roomname: roomname.trim(),
      roomHostid: userid,
      roomHostName: username,
      isPrivate: isPrivateBool,
      password,
      roomCreatedOnDate: dateStr,
      roomCreatedOnTime: timeStr,
      canvasState: []
    };

    if (isMongoConnected()) {
      const newRoom = new Room(roomData);
      await newRoom.save();
    } else {
      memoryStore.saveRoom(roomData);
    }

    return res.status(201).json({
      success: true,
      message: 'Room created successfully!',
      room: {
        roomid: roomData.roomid,
        roomname: roomData.roomname,
        roomHostid: roomData.roomHostid,
        roomHostName: roomData.roomHostName,
        isPrivate: roomData.isPrivate,
        password: roomData.password,
        roomCreatedOnDate: roomData.roomCreatedOnDate,
        roomCreatedOnTime: roomData.roomCreatedOnTime
      }
    });
  } catch (error) {
    console.error('Create Room Error:', error);
    return res.status(500).json({ success: false, message: 'Internal server error while creating room.' });
  }
};

/**
 * Validate and Join Room via HTTP check before WebSocket connection
 * Requirements: user must enter roomid and room name in order to join
 * If private, also provide password
 */
exports.joinRoomCheck = async (req, res) => {
  try {
    const { roomid, roomname, password } = req.body;

    if (!roomid || !roomname) {
      return res.status(400).json({ success: false, message: 'Both Room ID and Room Name are required.' });
    }

    const cleanRoomId = roomid.trim().toUpperCase();
    const cleanRoomName = roomname.trim();

    let room = null;
    if (isMongoConnected()) {
      room = await Room.findOne({ roomid: cleanRoomId });
    } else {
      room = memoryStore.findRoomById(cleanRoomId);
    }

    if (!room) {
      return res.status(404).json({ success: false, message: 'Room not found. Check your Room ID.' });
    }

    // Check Room Name match (case-insensitive for good UX)
    if (room.roomname.toLowerCase() !== cleanRoomName.toLowerCase()) {
      return res.status(400).json({
        success: false,
        message: `Room Name does not match Room ID '${cleanRoomId}'.`
      });
    }

    // Check if private and password required
    if (room.isPrivate) {
      if (!password || password.trim().toUpperCase() !== room.password.toUpperCase()) {
        return res.status(401).json({
          success: false,
          isPrivate: true,
          message: 'Invalid room password. This room is private.'
        });
      }
    }

    return res.status(200).json({
      success: true,
      message: 'Access granted to room!',
      room: {
        roomid: room.roomid,
        roomname: room.roomname,
        roomHostid: room.roomHostid,
        roomHostName: room.roomHostName,
        isPrivate: room.isPrivate,
        roomCreatedOnDate: room.roomCreatedOnDate,
        roomCreatedOnTime: room.roomCreatedOnTime
      }
    });
  } catch (error) {
    console.error('Join Room Check Error:', error);
    return res.status(500).json({ success: false, message: 'Internal server error while verifying room.' });
  }
};

/**
 * Get Room details
 */
exports.getRoom = async (req, res) => {
  try {
    const { roomid } = req.params;
    const cleanRoomId = roomid.trim().toUpperCase();

    let room = null;
    if (isMongoConnected()) {
      room = await Room.findOne({ roomid: cleanRoomId });
    } else {
      room = memoryStore.findRoomById(cleanRoomId);
    }

    if (!room) {
      return res.status(404).json({ success: false, message: 'Room not found.' });
    }

    return res.status(200).json({
      success: true,
      room: {
        roomid: room.roomid,
        roomname: room.roomname,
        roomHostid: room.roomHostid,
        roomHostName: room.roomHostName,
        isPrivate: room.isPrivate,
        password: room.password, // sent so host or authorized members can see
        roomCreatedOnDate: room.roomCreatedOnDate,
        roomCreatedOnTime: room.roomCreatedOnTime,
        canvasState: room.canvasState || []
      }
    });
  } catch (error) {
    console.error('Get Room Error:', error);
    return res.status(500).json({ success: false, message: 'Failed to retrieve room details.' });
  }
};
